using Microsoft.Extensions.Options;
using TaskBoard.Application.Abstractions.Storage;

namespace TaskBoard.Infrastructure.Storage;

internal sealed class LocalFileStorage(IOptions<FileStorageOptions> options, TimeProvider timeProvider) : IFileStorage
{
    private const int BufferSize = 81920;

    private string RootPath => Path.GetFullPath(options.Value.LocalRootPath);

    public async Task<string> UploadAsync(Stream content, string contentType, CancellationToken cancellationToken)
    {
        var storageKey = $"{timeProvider.GetUtcNow():yyyy/MM}/{Guid.NewGuid():N}";
        var path = GetSafePath(storageKey);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        await using var file = new FileStream(
            path, FileMode.CreateNew, FileAccess.Write, FileShare.None, BufferSize, useAsync: true);
        await content.CopyToAsync(file, cancellationToken);

        return storageKey;
    }

    public Task<Stream?> OpenReadAsync(string storageKey, CancellationToken cancellationToken)
    {
        var path = GetSafePath(storageKey);
        Stream? stream = File.Exists(path)
            ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, BufferSize, useAsync: true)
            : null;

        return Task.FromResult(stream);
    }

    public Task DeleteAsync(string storageKey, CancellationToken cancellationToken)
    {
        var path = GetSafePath(storageKey);
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    public IAsyncEnumerable<StoredFile> ListAsync(CancellationToken cancellationToken)
    {
        var root = RootPath;
        if (!Directory.Exists(root))
        {
            return AsyncEnumerable.Empty<StoredFile>();
        }

        // Keys always use '/', whatever the platform's separator.
        return Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories)
            .Select(path => new StoredFile(
                Path.GetRelativePath(root, path).Replace(Path.DirectorySeparatorChar, '/'),
                File.GetLastWriteTimeUtc(path)))
            .ToAsyncEnumerable();
    }

    // Defense in depth against path traversal, even though keys are always generated by this class.
    private string GetSafePath(string storageKey)
    {
        var root = RootPath;
        var path = Path.GetFullPath(Path.Combine(root, storageKey));

        if (!path.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new InvalidOperationException("Invalid storage key.");
        }

        return path;
    }
}
